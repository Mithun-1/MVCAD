import { test, expect } from '@playwright/test';

test('part title edits persist, support undo and export, and preserve feature drafts', async ({ page }) => {
  await page.setViewportSize({ width: 894, height: 884 });
  await page.goto('/');
  await expect(page.getByText('Engine ready', { exact: true })).toBeVisible();
  const title = page.getByRole('button', { name: 'Rename part', exact: true });
  const input = page.getByRole('textbox', { name: 'Part name', exact: true });
  const brand = (await page.locator('.brand').boundingBox())!;
  const titleBounds = (await title.boundingBox())!;
  expect(titleBounds.x - brand.x - brand.width).toBeLessThan(24);
  await title.click();
  await expect(input).toBeFocused();
  await input.fill('   ');
  await input.press('Enter');
  await expect(input).toHaveAttribute('aria-invalid', 'true');
  await input.press('Escape');
  await expect(title).toContainText('Untitled part');
  await title.click();
  await input.fill('  Mounting bracket  ');
  await input.press('Enter');
  await expect(title).toContainText('Mounting bracket');
  await expect(page.getByRole('button', { name: 'Mounting bracket', exact: true })).toBeVisible();
  await expect(title).toBeFocused();
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(title).toContainText('Untitled part');
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await expect(title).toContainText('Mounting bracket');
  await page.reload();
  await expect(title).toContainText('Mounting bracket');
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export', exact: true }).click();
  await page.getByRole('combobox', { name: 'Export format', exact: true }).selectOption('mvcad');
  await page.getByRole('button', { name: 'Export MVCAD', exact: true }).click();
  expect((await download).suggestedFilename()).toBe('Mounting bracket.mvcad');
  await page.getByRole('button', { name: 'Reference plane', exact: true }).click();
  await page.getByLabel('Name', { exact: true }).fill('Unsaved plane');
  await title.click();
  await input.fill('Cancelled name');
  await input.press('Escape');
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue('Unsaved plane');
  await expect(title).toContainText('Mounting bracket');
  await title.click();
  await input.fill('Fixture');
  await page.getByRole('heading', { name: 'Design tree', exact: true }).click();
  await expect(title).toContainText('Fixture');
  await page.getByRole('button', { name: 'Dark mode', exact: true }).click();
  await page.screenshot({ path: 'test-results/editable-part-title.png' });
  await title.click();
  await input.fill('F'.repeat(100));
  await input.press('Enter');
  await expect(page.getByRole('button', { name: 'Help and shortcuts', exact: true })).toBeInViewport();
  const rootName = await page.evaluate(() => JSON.parse(localStorage.getItem('mvcad.document.v1')!).name);
  expect(rootName).toBe('F'.repeat(100));
});
